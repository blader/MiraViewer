import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { format, resolveConfig } from 'prettier';

// Use the protobuf schema from the pinned ORT dependency, not a new encoder or
// downloaded model. These graphs are synthetic test instruments, not medical models.
const root = resolve(import.meta.dirname, '..');
const require = createRequire(import.meta.url);
const { onnx } = require(resolve(root, 'node_modules/onnxruntime-web/lib/onnxjs/ort-schema/protobuf/onnx.js'));
const value = (name, channels) => ({
  name,
  type: {
    tensorType: {
      elemType: 1,
      shape: {
        dim: [{ dimValue: 1 }, { dimValue: channels }, { dimParam: 'Z' }, { dimParam: 'Y' }, { dimParam: 'X' }],
      },
    },
  },
});
const scalar = (name, value) => ({ name, dims: [1], dataType: 1, floatData: [value] });
const integers = (name, ints) => ({ name, type: 7, ints });
const concat = {
  opType: 'Concat',
  input: ['zero', 'positive', 'inverse', 'negative'],
  output: ['logits'],
  attribute: [{ name: 'axis', type: 2, i: 1 }],
};
const small = {
  name: 'synthetic_pointwise_class_oracle',
  input: [value('input', 1)],
  output: [value('logits', 4)],
  initializer: [scalar('z', 0), scalar('one', 1), scalar('minus', -1)],
  node: [
    { opType: 'Mul', input: ['input', 'z'], output: ['zero'] },
    { opType: 'Identity', input: ['input'], output: ['positive'] },
    { opType: 'Sub', input: ['one', 'input'], output: ['inverse'] },
    { opType: 'Mul', input: ['input', 'minus'], output: ['negative'] },
    concat,
  ],
};
// A real 20 MiB initializer remains live: data-dependent Gather prevents constant
// folding it away. Store its recipe, not 20 MiB of generated fixture bytes.
const calibrationWeights = Buffer.alloc(20 * 1024 ** 2);
for (let offset = 0; offset < calibrationWeights.length; offset += 4) calibrationWeights.writeFloatLE(1, offset);
const calibration = {
  ...small,
  name: 'synthetic_20mib_weight_admission_oracle',
  initializer: [
    ...small.initializer,
    { name: 'weights', dims: [calibrationWeights.length / 4], dataType: 1, rawData: calibrationWeights },
  ],
  node: [
    { opType: 'Cast', input: ['input'], output: ['indices'], attribute: [{ name: 'to', type: 2, i: 7 }] },
    { opType: 'Gather', input: ['weights', 'indices'], output: ['scale'] },
    { opType: 'Mul', input: ['input', 'scale'], output: ['scaled'] },
    ...small.node.map((node) => ({
      ...node,
      input: node.input.map((input) => (input === 'input' ? 'scaled' : input)),
    })),
  ],
};
const weights = (name, dims) => ({
  name,
  dims,
  dataType: 1,
  floatData: Array(dims.reduce((a, b) => a * b, 1)).fill(1 / dims.slice(1).reduce((a, b) => a * b, 1)),
});
const slow = {
  name: 'synthetic_convolution_cancellation_workload',
  input: [value('input', 1)],
  output: [value('logits', 4)],
  initializer: [
    weights('entry', [8, 1, 3, 3, 3]),
    weights('repeat', [8, 8, 3, 3, 3]),
    weights('exit', [4, 8, 1, 1, 1]),
  ],
  node: Array.from({ length: 48 }, (_, index) => ({
    opType: 'Conv',
    input: [index === 0 ? 'input' : `layer${index - 1}`, index === 0 ? 'entry' : 'repeat'],
    output: [`layer${index}`],
    attribute: [integers('kernel_shape', [3, 3, 3]), integers('pads', [1, 1, 1, 1, 1, 1])],
  })).concat([
    {
      opType: 'Conv',
      input: ['layer47', 'exit'],
      output: ['logits'],
      attribute: [integers('kernel_shape', [1, 1, 1])],
    },
  ]),
};
const encode = (graph) => {
  const model = onnx.ModelProto.fromObject({
    irVersion: 8,
    opsetImport: [{ version: 13 }],
    producerName: 'MiraViewer synthetic browser tests',
    graph,
  });
  const error = onnx.ModelProto.verify(model);
  if (error) throw new Error(error);
  return Buffer.from(onnx.ModelProto.encode(model).finish());
};
const calibrationBytes = encode(calibration);
const weightsOffset = calibrationBytes.indexOf(calibrationWeights.subarray(0, 64));
if (
  weightsOffset < 0 ||
  !calibrationBytes.subarray(weightsOffset, weightsOffset + calibrationWeights.length).equals(calibrationWeights)
)
  throw new Error('The calibration graph does not contain its complete initializer.');
const parts = [
  calibrationBytes.subarray(0, weightsOffset),
  calibrationBytes.subarray(weightsOffset + calibrationWeights.length),
].map((part) => part.toString('base64'));
const text = `// Generated by scripts/generate-custom-model-fixtures.mjs; synthetic only.\nimport { TUMOR_MODEL_MANIFEST_EXAMPLE } from '../../src/utils/segmentation/onnx/modelManifest';\n\nconst MODELS = ${JSON.stringify({ small: encode(small).toString('base64'), slow: encode(slow).toString('base64') }, null, 2)} as const;\nconst CALIBRATION_PARTS = ${JSON.stringify(parts)};\nconst decode = (value: string) => Uint8Array.from(atob(value), (character) => character.charCodeAt(0));\n\nexport async function createSyntheticCustomModel(kind: keyof typeof MODELS | 'calibration') {\n  let bytes: Uint8Array<ArrayBuffer>;\n  if (kind === 'calibration') {\n    const [prefix, suffix] = CALIBRATION_PARTS.map(decode);\n    const weightBytes = 20 * 1024 ** 2;\n    bytes = new Uint8Array(prefix!.length + weightBytes + suffix!.length);\n    bytes.set(prefix!);\n    // Little-endian float32 ones, independent of host endianness.\n    for (let offset = prefix!.length; offset < prefix!.length + weightBytes; offset += 4) { bytes[offset + 2] = 128; bytes[offset + 3] = 63; }\n    bytes.set(suffix!, prefix!.length + weightBytes);\n  } else bytes = decode(MODELS[kind]);\n  const digest = await crypto.subtle.digest('SHA-256', bytes);\n  const modelSha256 = Array.from(new Uint8Array(digest), (byte) => byte.toString(16).padStart(2, '0')).join('');\n  const model = new File([bytes], 'synthetic-' + kind + '.onnx');\n  const manifest = new File([JSON.stringify({ ...TUMOR_MODEL_MANIFEST_EXAMPLE, input: { ...TUMOR_MODEL_MANIFEST_EXAMPLE.input, spatialFrame: 'source-grid' }, modelSha256 })], 'synthetic-' + kind + '.json', { type: 'application/json' });\n  return [model, manifest] as const;\n}\n`;
const output = resolve(root, 'tests/helpers/customTumorModel.ts');
const formatted = await format(text, { ...(await resolveConfig(output)), filepath: output });
if (process.argv.includes('--check')) {
  if (readFileSync(output, 'utf8') !== formatted)
    throw new Error('Synthetic model fixtures differ from their generator.');
} else writeFileSync(output, formatted);
